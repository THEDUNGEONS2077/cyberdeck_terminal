/**
 * vite.config.ts: build, dev server and tests (Vitest) for cyberdeck_terminal.
 *
 * CYBERDECK_BASE sets the site path: "/" locally, "/cyberdeck_terminal/" for
 * GitHub Pages (scripts/deploy.sh). `@/` points at src/.
 *
 * The service-worker plugin is quest_log_desktop's, renamed: the page is
 * Chrome's homepage and startup page, so it should open instantly (and work
 * offline) from a stored copy of the build.
 *
 * The bridge plugin packs the bridge extension (bridge/) as
 * cyberdeck-bridge.zip next to the page, for the CONNECT prompt's download.
 */
import react from '@vitejs/plugin-react';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Plugin } from 'vite';
import { defineConfig } from 'vitest/config';

import { makeZip } from './scripts/zip.ts';

// The version (package.json) and build number (the newest CHANGELOG.md entry), shown in SYSTEM and in backups.
const pkg = JSON.parse(readFileSync(new URL('./package.json', import.meta.url), 'utf8')) as { version: string };
const build = Number(/\(build (\d+)\)/.exec(readFileSync(new URL('./CHANGELOG.md', import.meta.url), 'utf8'))?.[1] ?? 0);

const base = process.env.CYBERDECK_BASE ?? '/';

/**
 * Writes dist/sw.js after a build: a service worker that stores every file
 * of this build, so the page opens from this computer, not the network.
 *
 *   - The page itself is served from the store first (optimization pass,
 *     2026-10-22): a New Tab page is opened all day, and asking the network
 *     first cost a full round trip before anything could start. Updates
 *     still arrive: on every open the browser checks sw.js itself, and a
 *     new build installs in the background and shows from the next open.
 *   - Other files (named by their content, so never stale) come from the
 *     store first too.
 *   - Installing fetches every file past the browser's HTTP cache
 *     (`cache: 'reload'`), so a new build can never store an old page.
 *   - The previous build's store is kept (only older ones are deleted), so
 *     a page still open on the old build can load the rest of its files.
 *
 * The cache name starts with the build time (so names sort oldest first)
 * and ends with a hash of the files. Its prefix is this app's own:
 * quest_log_desktop lives on the same origin, and each app only ever
 * deletes its own caches.
 */
function serviceWorker(): Plugin {
  // The build's output folder (dist/ unless --outDir says otherwise).
  let out = fileURLToPath(new URL('./dist', import.meta.url));
  return {
    name: 'cyberdeck-service-worker',
    apply: 'build',
    configResolved(config) {
      out = resolve(config.root, config.build.outDir);
    },
    closeBundle() {
      const files: string[] = [];
      const walk = (dir: string) => {
        for (const name of readdirSync(dir)) {
          const p = join(dir, name);
          if (statSync(p).isDirectory()) walk(p);
          else if (name !== 'sw.js') files.push(relative(out, p).split('\\').join('/'));
        }
      };
      walk(out);
      files.sort();
      const hash = createHash('sha256');
      for (const f of files) hash.update(f).update(readFileSync(join(out, f)));
      const version = `${new Date().toISOString().replace(/\D/g, '').slice(0, 14)}-${hash.digest('hex').slice(0, 12)}`;
      const urls = [base, ...files.filter((f) => f !== 'index.html').map((f) => `${base}${f}`)];
      writeFileSync(
        join(out, 'sw.js'),
        `// sw.js: cyberdeck_terminal's service worker (generated by vite.config.ts; don't edit).
// Keeps a copy of every file of this build, and serves the page from it: it opens
// without waiting for the network. A new build installs in the background (the
// browser checks this file on every open) and shows from the next open.
const PREFIX = 'cyberdeck_terminal-';
const CACHE = PREFIX + '${version}';
const INDEX = '${base}';
const FILES = ${JSON.stringify(urls, null, 2)};

self.addEventListener('install', (event) => {
  // Past the HTTP cache: a new build must never store an old copy of a file.
  const requests = FILES.map((url) => new Request(url, { cache: 'reload' }));
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(requests)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  // Keep this build and the one before (a page still open on it may need its files); delete older ones.
  event.waitUntil(
    caches
      .keys()
      .then((keys) => {
        const ours = keys.filter((k) => k.startsWith(PREFIX)).sort();
        const keep = new Set([CACHE, ...ours.filter((k) => k < CACHE).slice(-1)]);
        return Promise.all(ours.filter((k) => !keep.has(k)).map((k) => caches.delete(k)));
      })
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  // Only this app's files: quest_log_desktop shares the origin and has its own worker.
  if (!new URL(request.url).pathname.startsWith(INDEX)) return;
  if (request.mode === 'navigate') {
    // The page from the store first: no network round trip before it can start.
    event.respondWith(caches.match(INDEX, { cacheName: CACHE }).then((hit) => hit || fetch(request)).catch(() => caches.match(INDEX)));
    return;
  }
  event.respondWith(caches.match(request).then((hit) => hit || fetch(request)));
});
`,
      );
    },
  };
}

/**
 * Adds cyberdeck-bridge.zip to the build: every file in bridge/ inside a
 * `cyberdeck-bridge/` folder (so unzipping makes one folder to load in
 * chrome://extensions). Emitted as a build asset, so it's in dist/ before
 * the service worker lists the files.
 */
function bridgeZip(): Plugin {
  return {
    name: 'cyberdeck-bridge-zip',
    apply: 'build',
    generateBundle() {
      const dir = fileURLToPath(new URL('./bridge', import.meta.url));
      const entries: { name: string; data: Buffer }[] = [];
      const walk = (sub: string) => {
        for (const name of readdirSync(join(dir, sub)).sort()) {
          const rel = sub ? `${sub}/${name}` : name;
          if (statSync(join(dir, rel)).isDirectory()) walk(rel);
          else entries.push({ name: `cyberdeck-bridge/${rel}`, data: readFileSync(join(dir, rel)) });
        }
      };
      walk('');
      this.emitFile({ type: 'asset', fileName: 'cyberdeck-bridge.zip', source: makeZip(entries) });
    },
  };
}

export default defineConfig({
  base,
  plugins: [react(), bridgeZip(), serviceWorker()],
  define: { __APP_VERSION__: JSON.stringify(pkg.version), __APP_BUILD__: String(build) },
  resolve: { alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) } },
  // ES2022: the entry point awaits persistence before rendering (top-level await).
  build: { outDir: 'dist', sourcemap: false, target: 'es2022' },
  test: {
    globals: true,
    // Logic tests run in Node; DOM tests opt in with `// @vitest-environment jsdom`.
    environment: 'node',
    include: ['src/**/*.test.{ts,tsx}'],
  },
});
