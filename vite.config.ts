/**
 * vite.config.ts: build, dev server and tests (Vitest) for cyberdeck_terminal.
 *
 * CYBERDECK_BASE sets the site path: "/" locally, "/cyberdeck_terminal/" for
 * GitHub Pages (scripts/deploy.sh). `@/` points at src/.
 *
 * The service-worker plugin is quest_log_desktop's, renamed: the page is
 * Chrome's homepage and startup page, so it should open instantly (and work
 * offline) from a stored copy of the build.
 */
import react from '@vitejs/plugin-react';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Plugin } from 'vite';
import { defineConfig } from 'vitest/config';

// The version (package.json) and build number (the newest CHANGELOG.md entry), shown in SYSTEM and in backups.
const pkg = JSON.parse(readFileSync(new URL('./package.json', import.meta.url), 'utf8')) as { version: string };
const build = Number(/\(build (\d+)\)/.exec(readFileSync(new URL('./CHANGELOG.md', import.meta.url), 'utf8'))?.[1] ?? 0);

const base = process.env.CYBERDECK_BASE ?? '/';

/**
 * Writes dist/sw.js after a build: a service worker that stores every file
 * of this build. Its cache name is a hash of the files, so a new build
 * replaces the old copy on the next visit. Pages try the network first (to
 * pick up a new version) and fall back to the stored copy; other files come
 * from the store first (their names change with each build).
 *
 * The cache prefix is this app's own: quest_log_desktop lives on the same
 * origin, and each app only ever deletes its own caches.
 */
function serviceWorker(): Plugin {
  return {
    name: 'cyberdeck-service-worker',
    apply: 'build',
    closeBundle() {
      const out = fileURLToPath(new URL('./dist', import.meta.url));
      const files: string[] = [];
      const walk = (dir: string) => {
        for (const name of readdirSync(dir)) {
          const p = join(dir, name);
          if (statSync(p).isDirectory()) walk(p);
          else if (name !== 'sw.js') files.push(relative(out, p).split('\\').join('/'));
        }
      };
      walk(out);
      files.sort();
      const hash = createHash('sha256');
      for (const f of files) hash.update(f).update(readFileSync(join(out, f)));
      const version = hash.digest('hex').slice(0, 12);
      const urls = [base, ...files.filter((f) => f !== 'index.html').map((f) => `${base}${f}`)];
      writeFileSync(
        join(out, 'sw.js'),
        `// sw.js: cyberdeck_terminal's service worker (generated by vite.config.ts; don't edit).
// Keeps a copy of every file of this build so the page opens instantly and offline.
const CACHE = 'cyberdeck_terminal-${version}';
const INDEX = '${base}';
const FILES = ${JSON.stringify(urls, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('cyberdeck_terminal-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  // Only this app's files: quest_log_desktop shares the origin and has its own worker.
  if (!new URL(request.url).pathname.startsWith(INDEX)) return;
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match(INDEX)));
    return;
  }
  event.respondWith(caches.match(request).then((hit) => hit || fetch(request)));
});
`,
      );
    },
  };
}

export default defineConfig({
  base,
  plugins: [react(), serviceWorker()],
  define: { __APP_VERSION__: JSON.stringify(pkg.version), __APP_BUILD__: String(build) },
  resolve: { alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) } },
  // ES2022: the entry point awaits persistence before rendering (top-level await).
  build: { outDir: 'dist', sourcemap: false, target: 'es2022' },
  test: {
    globals: true,
    // Logic tests run in Node; DOM tests opt in with `// @vitest-environment jsdom`.
    environment: 'node',
    include: ['src/**/*.test.{ts,tsx}'],
  },
});
